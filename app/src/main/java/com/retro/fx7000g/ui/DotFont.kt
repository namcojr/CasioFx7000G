package com.retro.fx7000g.ui

/**
 * A compact 5x7 dot-matrix font covering exactly the glyphs the FX-7000G LCD
 * needs to render (digits, operators, the trig/log function names, mode labels
 * and the special symbols × ÷ √ π ² ⁻¹). Each glyph is 7 rows of 5 columns,
 * with '#' meaning a lit dot.
 */
object DotFont {

    const val WIDTH = 5
    const val HEIGHT = 7

    private fun g(vararg rows: String): Array<String> {
        require(rows.size == HEIGHT) { "glyph must have $HEIGHT rows" }
        return arrayOf(*rows)
    }

    private val blank = g(
        "     ",
        "     ",
        "     ",
        "     ",
        "     ",
        "     ",
        "     "
    )

    private val glyphs: Map<Char, Array<String>> = mapOf(
        '0' to g(" ### ", "#   #", "#  ##", "# # #", "##  #", "#   #", " ### "),
        '1' to g("  #  ", " ##  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### "),
        '2' to g(" ### ", "#   #", "    #", "   # ", "  #  ", " #   ", "#####"),
        '3' to g("#####", "   # ", "  #  ", "   # ", "    #", "#   #", " ### "),
        '4' to g("   # ", "  ## ", " # # ", "#  # ", "#####", "   # ", "   # "),
        '5' to g("#####", "#    ", "#### ", "    #", "    #", "#   #", " ### "),
        '6' to g("  ## ", " #   ", "#    ", "#### ", "#   #", "#   #", " ### "),
        '7' to g("#####", "    #", "   # ", "  #  ", " #   ", " #   ", " #   "),
        '8' to g(" ### ", "#   #", "#   #", " ### ", "#   #", "#   #", " ### "),
        '9' to g(" ### ", "#   #", "#   #", " ####", "    #", "   # ", " ##  "),

        '.' to g("     ", "     ", "     ", "     ", "     ", "  ## ", "  ## "),
        '-' to g("     ", "     ", "     ", "#####", "     ", "     ", "     "),
        '\u2212' to g("     ", "     ", "     ", "#####", "     ", "     ", "     "),
        '+' to g("     ", "  #  ", "  #  ", "#####", "  #  ", "  #  ", "     "),
        '(' to g("   # ", "  #  ", " #   ", " #   ", " #   ", "  #  ", "   # "),
        ')' to g(" #   ", "  #  ", "   # ", "   # ", "   # ", "  #  ", " #   "),
        '!' to g("  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "     ", "  #  "),
        '^' to g("  #  ", " # # ", "#   #", "     ", "     ", "     ", "     "),
        '=' to g("     ", "     ", "#####", "     ", "#####", "     ", "     "),
        ' ' to blank,

        '\u00D7' to g("     ", "     ", "#   #", " # # ", "  #  ", " # # ", "#   #"), // ×
        '\u00F7' to g("     ", "  #  ", "     ", "#####", "     ", "  #  ", "     "), // ÷
        '\u221A' to g("   ##", "   # ", "   # ", "#  # ", " # # ", " # # ", "  #  "), // √
        '\u03C0' to g("     ", "     ", "#####", " # # ", " # # ", " # # ", "#   #"), // π
        '\u00B2' to g(" ##  ", "#  # ", "  #  ", " #   ", "#### ", "     ", "     "), // ²
        '\u207B' to g("###  ", "     ", "     ", "     ", "     ", "     ", "     "), // ⁻
        '\u00B9' to g(" #   ", "##   ", " #   ", " #   ", "###  ", "     ", "     "), // ¹

        'A' to g(" ### ", "#   #", "#   #", "#####", "#   #", "#   #", "#   #"),
        'B' to g("#### ", "#   #", "#   #", "#### ", "#   #", "#   #", "#### "),
        'C' to g(" ### ", "#   #", "#    ", "#    ", "#    ", "#   #", " ### "),
        'D' to g("#### ", "#   #", "#   #", "#   #", "#   #", "#   #", "#### "),
        'E' to g("#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#####"),
        'F' to g("#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#    "),
        'G' to g(" ### ", "#   #", "#    ", "# ###", "#   #", "#   #", " ### "),
        'H' to g("#   #", "#   #", "#   #", "#####", "#   #", "#   #", "#   #"),
        'I' to g("#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "#####"),
        'J' to g("  ###", "   # ", "   # ", "   # ", "#  # ", "#  # ", " ##  "),
        'K' to g("#   #", "#  # ", "# #  ", "##   ", "# #  ", "#  # ", "#   #"),
        'L' to g("#    ", "#    ", "#    ", "#    ", "#    ", "#    ", "#####"),
        'M' to g("#   #", "## ##", "# # #", "# # #", "#   #", "#   #", "#   #"),
        'N' to g("#   #", "##  #", "# # #", "#  ##", "#   #", "#   #", "#   #"),
        'O' to g(" ### ", "#   #", "#   #", "#   #", "#   #", "#   #", " ### "),
        'P' to g("#### ", "#   #", "#   #", "#### ", "#    ", "#    ", "#    "),
        'Q' to g(" ### ", "#   #", "#   #", "#   #", "# # #", "#  # ", " ## #"),
        'R' to g("#### ", "#   #", "#   #", "#### ", "# #  ", "#  # ", "#   #"),
        'S' to g(" ####", "#    ", "#    ", " ### ", "    #", "    #", "#### "),
        'T' to g("#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  "),
        'U' to g("#   #", "#   #", "#   #", "#   #", "#   #", "#   #", " ### "),
        'V' to g("#   #", "#   #", "#   #", "#   #", " # # ", " # # ", "  #  "),
        'W' to g("#   #", "#   #", "#   #", "# # #", "# # #", "## ##", "#   #"),
        'X' to g("#   #", "#   #", " # # ", "  #  ", " # # ", "#   #", "#   #"),
        'Y' to g("#   #", "#   #", " # # ", "  #  ", "  #  ", "  #  ", "  #  "),
        'Z' to g("#####", "    #", "   # ", "  #  ", " #   ", "#    ", "#####"),

        'a' to g("     ", "     ", " ### ", "    #", " ####", "#   #", " ####"),
        'b' to g("#    ", "#    ", "#### ", "#   #", "#   #", "#   #", "#### "),
        'c' to g("     ", "     ", " ### ", "#    ", "#    ", "#    ", " ### "),
        'd' to g("    #", "    #", " ####", "#   #", "#   #", "#   #", " ####"),
        'e' to g("     ", "     ", " ### ", "#   #", "#####", "#    ", " ### "),
        'f' to g("  ## ", " #   ", "###  ", " #   ", " #   ", " #   ", " #   "),
        'g' to g("     ", "     ", " ####", "#   #", " ####", "    #", " ### "),
        'h' to g("#    ", "#    ", "# ## ", "##  #", "#   #", "#   #", "#   #"),
        'i' to g("  #  ", "     ", " ##  ", "  #  ", "  #  ", "  #  ", " ### "),
        'j' to g("    #", "     ", "   ##", "    #", "    #", "#   #", " ### "),
        'k' to g("#    ", "#    ", "#  # ", "# #  ", "##   ", "# #  ", "#  # "),
        'l' to g(" ##  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### "),
        'm' to g("     ", "     ", "## ##", "# # #", "# # #", "#   #", "#   #"),
        'n' to g("     ", "     ", "# ## ", "##  #", "#   #", "#   #", "#   #"),
        'o' to g("     ", "     ", " ### ", "#   #", "#   #", "#   #", " ### "),
        'p' to g("     ", "     ", "#### ", "#   #", "#### ", "#    ", "#    "),
        'q' to g("     ", "     ", " ####", "#   #", " ####", "    #", "    #"),
        'r' to g("     ", "     ", "# ## ", "##  #", "#    ", "#    ", "#    "),
        's' to g("     ", "     ", " ####", "#    ", " ### ", "    #", "#### "),
        't' to g(" #   ", " #   ", "###  ", " #   ", " #   ", " #   ", "  ## "),
        'u' to g("     ", "     ", "#   #", "#   #", "#   #", "#   #", " ### "),
        'v' to g("     ", "     ", "#   #", "#   #", "#   #", " # # ", "  #  "),
        'w' to g("     ", "     ", "#   #", "#   #", "# # #", "# # #", " # # "),
        'x' to g("     ", "     ", "#   #", " # # ", "  #  ", " # # ", "#   #"),
        'y' to g("     ", "     ", "#   #", "#   #", " ####", "    #", " ### "),
        'z' to g("     ", "     ", "#####", "   # ", "  #  ", " #   ", "#####"),

        'm' to g("     ", "     ", "## # ", "# # #", "# # #", "# # #", "#   #"),
        'w' to g("     ", "     ", "#   #", "#   #", "# # #", "# # #", " # # "),

        '#' to g(" # # ", " # # ", "#####", " # # ", "#####", " # # ", " # # "),
        '%' to g("##  #", "##  #", "   # ", "  #  ", " #   ", "#  ##", "#  ##"),
        '/' to g("    #", "    #", "   # ", "  #  ", " #   ", "#    ", "#    "),
        '?' to g(" ### ", "#   #", "    #", "   # ", "  #  ", "     ", "  #  "),
        ',' to g("     ", "     ", "     ", "     ", "  ## ", "  #  ", " #   "),
        '\u00B0' to g(" ##  ", "#  # ", "#  # ", " ##  ", "     ", "     ", "     "), // °
        '\u2032' to g("  #  ", "  #  ", " #   ", "     ", "     ", "     ", "     "), // ′
        '\u2033' to g(" # # ", " # # ", "#  # ", "     ", "     ", "     ", "     "), // ″
        '\u02E3' to g("# #  ", " #   ", "# #  ", "     ", "     ", "     ", "     "), // ˣ
        '\u2192' to g("     ", "  #  ", "   # ", "#####", "   # ", "  #  ", "     ") // →
    )

    fun glyph(c: Char): Array<String> = glyphs[c] ?: blank
}
